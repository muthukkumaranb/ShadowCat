"""s4-t2: precursor evaluation of the stacked onset model and the LR baseline.

Onset label = future_attack_label (an attack window within t+1..t+5). Most onset-positive
windows are already inside an attack (label_binary = 1). A *precursor* is a window with
label_binary = 0 and future_attack_label = 1: no attack yet, attack within 5 minutes.
This script scores only precursors against windows that are benign and not precursors
(label_binary = 0, future_attack_label = 0), using the committed LOEO test predictions:

  stacked: ml1/artifacts/lstm/lstm_stacked/lstm_onset_loeo_test_predictions.csv, read with
           `git show` from commit a0687cf (branch feature/judge-readiness-v2, not on main),
           produced by evaluation/benchmark/reproduce_stacked_benchmark.py
  LR:      ml1/artifacts/lr_set_a_corrected/lr_onset_loeo_predictions.csv (on main)
  labels:  label_binary from data-engineering/data/ucs/ucs_windows.parquet at commit e200fdb,
           the dataset the stacked models were trained on (read with `git show`)

Reported per model: ROC-AUC (precursors vs benign-and-not-precursor), recall on precursors at
the matched-FPR (~5%) threshold (same procedure as reproduce_stacked_benchmark.py: highest
threshold with FPR <= 5% over all onset-negative test windows), and lead time in minutes from
each detected precursor to the first attack window (label_binary = 1) of its day.
Writes evaluation/precursor/precursor_results.json.
"""
import io
import json
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

REPO = Path(__file__).resolve().parents[2]
STACKED_REV, STACKED_PATH = "a0687cf", "ml1/artifacts/lstm/lstm_stacked/lstm_onset_loeo_test_predictions.csv"
DATA_REV, DATA_PATH = "e200fdb", "data-engineering/data/ucs/ucs_windows.parquet"
LR_PATH = "ml1/artifacts/lr_set_a_corrected/lr_onset_loeo_predictions.csv"
OUT = REPO / "evaluation/precursor/precursor_results.json"
DATASET_NOTE = ("(6-day dataset) the 10-day rebuild did not pass its check (fix/restore-10day-dataset, "
                "REBUILD_CHECK.json); these predictions are on the 6-day e200fdb dataset the models were trained on")


def write_md(out):
    d, t = out["dataset_counts"], out["test_counts"]
    rows = []
    for name, m in out["models"].items():
        lt = m["lead_time_minutes_detected_precursors"]
        lead = "—" if lt["n"] == 0 else f"{lt['mean']:.1f} (min {lt['min']:.0f}, max {lt['max']:.0f}, n={lt['n']})"
        rows.append(f"| {name} | {m['roc_auc_precursor_vs_benign_not_precursor']:.3f} | "
                    f"{m['precursors_detected']}/{t['precursor']} = {m['precursor_recall_at_matched_fpr']:.3f} | "
                    f"{m['matched_fpr_threshold']:.4f} | {m['fpr_on_benign_not_precursor_at_threshold']:.3f} | {lead} |")
    text = f"""# Precursor evaluation (6-day dataset)

Generated by `evaluation/precursor/precursor_eval.py`; every number is in `precursor_results.json`.
{DATASET_NOTE}.

A precursor window has no attack yet (label_binary = 0) but an attack within the next 5 minutes
(future_attack_label = 1). In the dataset {d['onset_positive']} windows are onset-positive: {d['in_progress_attack']}
are already inside an attack and only {d['precursor']} are precursors. The LOEO test set ({t['windows']} windows) holds
{t['precursor']} precursors, {t['benign_not_precursor']} benign non-precursor windows and {t['in_progress_attack']} in-progress attack windows.

Scored on precursors vs benign non-precursor windows only, using the committed LOEO test predictions
(stacked: `{out['sources']['stacked_predictions']}`; LR: `{out['sources']['lr_predictions']}`):

| Model | ROC-AUC (precursor vs benign) | Precursor recall at matched FPR | Threshold (FPR ~5% on all onset-negatives) | FPR on benign non-precursors | Lead time to first attack window, minutes |
|---|---|---|---|---|---|
""" + "\n".join(rows) + """

With so few precursors the recall estimates are coarse. The onset F1 reported elsewhere (0.9127) is measured
mostly on in-progress attack windows; on true precursors both models are weak.
"""
    (OUT.parent / "PRECURSOR.md").write_text(text)


def git_bytes(rev, path):
    return subprocess.run(["git", "show", f"{rev}:{path}"], cwd=REPO, capture_output=True, check=True).stdout


def matched_fpr_threshold(y, p, target=0.05):
    best = None
    for t in np.unique(p)[::-1]:
        pred = p >= t
        fpr = (pred & (y == 0)).sum() / (y == 0).sum()
        if fpr <= target:
            best = t
        else:
            break
    return float(best)


def main():
    data = pd.read_parquet(io.BytesIO(git_bytes(DATA_REV, DATA_PATH)))
    data["ts"] = pd.to_datetime(data["window_start_utc"], utc=True)
    data = data.sort_values("ts").reset_index(drop=True)

    stacked = pd.read_csv(io.BytesIO(git_bytes(STACKED_REV, STACKED_PATH)))
    lr = pd.read_csv(REPO / LR_PATH)
    for d in (stacked, lr):
        d["ts"] = pd.to_datetime(d["timestamp"], utc=True)
    df = stacked.merge(lr[["fold_id", "ts", "y_probability"]], on=["fold_id", "ts"], suffixes=("_stacked", "_lr"))
    assert len(df) == len(stacked) == len(lr), "stacked and LR test windows do not align"
    df = df.merge(data[["ts", "label_binary", "future_attack_label", "source_day"]], on="ts", how="left")
    assert df["label_binary"].notna().all(), "test window missing from the e200fdb dataset"
    assert (df["future_attack_label"] == df["y_true"]).all(), "onset label mismatch"

    is_prec = (df.label_binary == 0) & (df.future_attack_label == 1)
    is_neg = (df.label_binary == 0) & (df.future_attack_label == 0)

    # first attack window per day, for lead time
    first_attack = {}
    for day, g in data[data.label_binary == 1].groupby("source_day"):
        first_attack[day] = g["ts"].sort_values().values

    def lead_minutes(row):
        times = first_attack.get(row.source_day)
        if times is None:
            return None
        later = times[times > np.datetime64(row.ts.tz_convert(None))]
        return float((later[0] - np.datetime64(row.ts.tz_convert(None))) / np.timedelta64(1, "m")) if len(later) else None

    full_onset_pos = int((data.future_attack_label == 1).sum())
    full_prec = int(((data.label_binary == 0) & (data.future_attack_label == 1)).sum())
    out = {
        "generated_by": "evaluation/precursor/precursor_eval.py",
        "sources": {"stacked_predictions": f"{STACKED_REV}:{STACKED_PATH}", "lr_predictions": LR_PATH,
                    "labels": f"{DATA_REV}:{DATA_PATH}"},
        "dataset_counts": {"windows": int(len(data)), "onset_positive": full_onset_pos,
                           "precursor": full_prec, "in_progress_attack": full_onset_pos - full_prec},
        "test_counts": {"windows": int(len(df)), "precursor": int(is_prec.sum()),
                        "benign_not_precursor": int(is_neg.sum()),
                        "in_progress_attack": int(((df.label_binary == 1)).sum())},
        "models": {},
    }
    y_all = df["y_true"].to_numpy(int)
    sub = df[is_prec | is_neg]
    for name, col in (("stacked_ensemble", "y_probability_stacked"), ("lr_baseline", "y_probability_lr")):
        thr = matched_fpr_threshold(y_all, df[col].to_numpy())
        prec = df[is_prec]
        detected = prec[prec[col] >= thr]
        leads = [lead_minutes(r) for r in detected.itertuples()]
        leads = [x for x in leads if x is not None]
        out["models"][name] = {
            "matched_fpr_threshold": thr,
            "roc_auc_precursor_vs_benign_not_precursor": float(roc_auc_score(is_prec[sub.index].astype(int), sub[col]))
            if is_prec.sum() and is_neg.sum() else None,
            "precursor_recall_at_matched_fpr": float(len(detected) / len(prec)) if len(prec) else None,
            "precursors_detected": int(len(detected)),
            "fpr_on_benign_not_precursor_at_threshold": float((df[is_neg][col] >= thr).mean()),
            "lead_time_minutes_detected_precursors": {
                "n": len(leads),
                "mean": float(np.mean(leads)) if leads else None,
                "min": float(np.min(leads)) if leads else None,
                "max": float(np.max(leads)) if leads else None,
            },
            "precursor_scores": [round(float(v), 6) for v in prec[col]],
        }
    out["dataset_note"] = DATASET_NOTE
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=2) + "\n")
    write_md(out)
    print(json.dumps({k: v for k, v in out.items() if k != "models"}, indent=2))
    for k, v in out["models"].items():
        print(k, {a: b for a, b in v.items() if a != "precursor_scores"})


if __name__ == "__main__":
    main()
